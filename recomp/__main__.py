"""Static recompiler driver.

    python -m recomp <game_dir> <out_dir> [--hle config/hle.txt]

Produces in <out_dir>:
    ppc_funcs.h       prototypes of all guest functions
    ppc_recomp_NN.c   lifted code, split in chunks
    ppc_functable.c   sorted address -> function table for indirect calls
    rel_image.bin     relocated REL sections, loaded by the runtime at REL_BASE
    stats.txt         summary
"""
import argparse
import glob
import os
import struct
import time

from .analyze import REL_BASE, Program, discover
from .lift import lift_function
from .sigdb import load_dsy, match_functions
from .symbols import build_symbols

CHUNK = 800


def load_symbol_overrides(path):
    """config/symbols.txt: names identified by hand, `<addr> <name>`."""
    out = {}
    if os.path.exists(path):
        for line in open(path):
            line = line.split("#")[0].split()
            if len(line) >= 2:
                out[int(line[0], 16)] = line[1]
    return out


def load_hle(path, by_name):
    """config/hle.txt: `<addr or symbol> <C function>`."""
    out = {}
    if path and os.path.exists(path):
        for n, line in enumerate(open(path), 1):
            line = line.split("#")[0].split()
            if len(line) < 2:
                continue
            key = line[0]
            if key in by_name:
                addr = by_name[key]
            else:
                try:
                    addr = int(key, 16)
                except ValueError:
                    raise SystemExit(f"{path}:{n}: unknown symbol {key}")
            out[addr] = line[1]
    return out


def collect_symbols(prog, funcs):
    names = build_symbols(prog, funcs)
    dsy = os.path.join("third_party", "dolphin", "totaldb.dsy")
    if os.path.exists(dsy):
        for a, n in match_functions(prog, funcs, load_dsy(dsy)).items():
            names.setdefault(a, n)
    names.update(load_symbol_overrides(os.path.join("config", "symbols.txt")))
    return names


def write_if_changed(path, text):
    if os.path.exists(path) and open(path, encoding="utf-8").read() == text:
        return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def rel_image(prog):
    img = bytearray(prog.rel_end - REL_BASE)
    for rel in prog.rels.values():
        for s in rel.sections:
            if s and s.data:
                img[s.addr - REL_BASE:s.addr - REL_BASE + s.size] = s.data
    return bytes(img)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("game_dir")
    ap.add_argument("out_dir")
    ap.add_argument("--hle", default="config/hle.txt")
    args = ap.parse_args()

    t0 = time.time()
    prog = Program(args.game_dir)
    funcs = discover(prog)
    starts = {f.start for f in funcs}
    names = collect_symbols(prog, funcs)
    by_name = {}
    for a, n in names.items():
        by_name.setdefault(n, a)
    hle = load_hle(args.hle, by_name)
    returns_twice = {by_name[n] for n in ("OSSaveContext",) if n in by_name}
    print(f"{len(funcs)} functions found, {len(names)} named, in {time.time() - t0:.1f}s")

    os.makedirs(args.out_dir, exist_ok=True)
    protos = ["/* generated by recomp — do not edit */", "#pragma once",
              '#include "ppc_context.h"', ""]
    protos += [f"void f_{f.start:08X}(PPCContext *c);" for f in funcs]
    protos += sorted({f"void {n}(PPCContext *c);" for n in hle.values()})
    write_if_changed(os.path.join(args.out_dir, "ppc_funcs.h"), "\n".join(protos) + "\n")

    unimpl = 0
    for k in range(0, len(funcs), CHUNK):
        lines = ['#include "ppc_funcs.h"', ""]
        for fn in funcs[k:k + CHUNK]:
            if fn.start in names:
                lines.append(f"/* {names[fn.start]} */")
            body = lift_function(prog, fn, starts, hle, returns_twice)
            unimpl += sum("ppc_unimplemented" in l for l in body)
            lines += body
        write_if_changed(os.path.join(args.out_dir, f"ppc_recomp_{k // CHUNK:03d}.c"),
                         "\n".join(lines) + "\n")

    # chunks left over from a previous run with more functions
    n_chunks = (len(funcs) + CHUNK - 1) // CHUNK
    for stale in glob.glob(os.path.join(args.out_dir, "ppc_recomp_*.c")):
        if int(os.path.basename(stale)[11:14]) >= n_chunks:
            os.remove(stale)

    table = ['#include "ppc_funcs.h"', "", "const ppc_func_entry_t g_ppc_funcs[] = {"]
    table += [f"\t{{0x{f.start:08X}u, f_{f.start:08X}}}," for f in funcs]
    table += ["};", f"const uint32_t g_ppc_func_count = {len(funcs)};", ""]
    write_if_changed(os.path.join(args.out_dir, "ppc_functable.c"), "\n".join(table))

    # symbol table for runtime diagnostics and lookups by name
    write_if_changed(os.path.join(args.out_dir, "symbols.txt"),
                     "".join(f"{a:08X} {names[a]}\n" for a in sorted(names)))
    syms = ['#include <stdint.h>', "",
            "typedef struct { uint32_t addr; const char *name; } sym_t;",
            "const sym_t g_ppc_symbols[] = {"]
    syms += [f'\t{{0x{a:08X}u, "{names[a]}"}},' for a in sorted(names)]
    syms += ["};", f"const uint32_t g_ppc_symbol_count = {len(names)};", ""]
    write_if_changed(os.path.join(args.out_dir, "ppc_symbols.c"), "\n".join(syms))

    # where each REL lives in our image, for the OSLink HLE
    rels = ['#include <stdint.h>', '#include "rel_table.h"', "", "const rel_info_t g_rel_table[] = {"]
    for rel in sorted(prog.rels.values(), key=lambda r: r.module_id):
        secs = [(s.addr, s.size, int(s.exec)) if s else (0, 0, 0) for s in rel.sections]
        addrs = ", ".join(f"0x{a:08X}u" for a, _, _ in secs)
        sizes = ", ".join(f"0x{n:X}u" for _, n, _ in secs)
        execs = ", ".join(str(e) for _, _, e in secs)
        rels.append(f'\t{{{rel.module_id}, "{rel.name}", {len(secs)}, '
                    f"0x{rel.symbol_addr(rel.prolog):08X}u, 0x{rel.symbol_addr(rel.epilog):08X}u, "
                    f"0x{rel.symbol_addr(rel.unresolved):08X}u, {{{addrs}}}, {{{sizes}}}, {{{execs}}}}},")
    rels += ["};", f"const uint32_t g_rel_count = {len(prog.rels)};", ""]
    write_if_changed(os.path.join(args.out_dir, "ppc_rels.c"), "\n".join(rels))

    with open(os.path.join(args.out_dir, "rel_image.bin"), "wb") as f:
        f.write(struct.pack(">II", REL_BASE, prog.rel_end - REL_BASE))
        f.write(rel_image(prog))

    stats = [f"functions: {len(funcs)}",
             f"jump tables: {sum(len(f.jump_tables) for f in funcs)}",
             f"unimplemented instructions: {unimpl}",
             f"HLE overrides: {len(hle)}",
             f"REL image: {REL_BASE:#x}-{prog.rel_end:#x}"]
    for rel in prog.rels.values():
        stats.append(f"  {rel.name} id={rel.module_id} prolog={rel.symbol_addr(rel.prolog):#x}")
    write_if_changed(os.path.join(args.out_dir, "stats.txt"), "\n".join(stats) + "\n")
    print("\n".join(stats))
    print(f"done in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
